function buildChapters(count, baseTitle) {
  return Array.from({ length: count }, (_, i) => ({
    id: `${baseTitle}-ch${String(i + 1).padStart(2, '0')}`,
    title: chapterTitles[baseTitle]?.[i] ?? `第 ${i + 1} 章 · 内容展开`,
    duration: 12 * 60 + Math.floor(Math.random() * 480), // 12-20 分钟
    free: i === 0,
  }));
}

